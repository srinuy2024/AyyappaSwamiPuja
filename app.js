function playHapticAndTrack(el) {
  if (navigator.vibrate) {
    navigator.vibrate(35);
  }
  if (el) {
    el.style.transform = "scale(0.97)";
    el.style.backgroundColor = "#fef08a";
    setTimeout(() => {
      el.style.transform = "";
      el.style.backgroundColor = "";
    }, 250);
  }
}

