function setSelectValue(id, val) {
  const el = document.getElementById(id);
  if (!el) return;
  for (let i = 0; i < el.options.length; i++) {
    if (el.options[i].value === val || el.options[i].value.includes(val)) {
      el.selectedIndex = i;
      break;
    }
  }
}

